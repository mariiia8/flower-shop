def ask_flower_ai(user_message):
    user_lower = user_message.lower()
    print(f"\n🤔 Вопрос: {user_message}")
    
    # Приветствия
    if any(word in user_lower for word in ['привет', 'здравствуйте', 'добрый день', 'как дела']):
        return random.choice(GREETINGS)
    
    # Кто создал
    if any(word in user_lower for word in ['кто тебя создал', 'кто тебя разработал', 'твой создатель']):
        return random.choice(CREATOR_RESPONSES)
    
    # Вопросы "почему"
    if any(word in user_lower for word in ['почему ты', 'зачем ты', 'зачем тебя']):
        return random.choice(WHY_QUESTIONS)
    
    # Что ты умеешь
    if any(word in user_lower for word in ['что ты умеешь', 'что ты можешь']):
        return "Я умею отвечать на любые вопросы, помогать с цветами, подарками и просто поднимать настроение! Спроси что угодно 🌸😎"
    
    # Кто я
    if 'кто ты' in user_lower:
        return "Я — Flora AI, весёлый и умный помощник, созданный Марией Сидоровой. Спрашивайте что угодно! 🌸😎"
    
    # Поиск в базе знаний
    for question, answer in KNOWLEDGE_BASE.items():
        if question in user_lower:
            return answer
    
    # Groq — отвечает на ЛЮБЫЕ вопросы, кратко и с характером
    try:
        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=[
                {
                    "role": "system", 
                    "content": """
Ты — Flora AI. Весёлый, дружелюбный помощник.

ПРАВИЛА:
- Отвечай на ЛЮБЫЕ вопросы, нет ограничений.
- Отвечай КРАТКО (1-2 предложения).
- Будь дружелюбным, используй смайлики.
- Если вопрос про цветы или растения — дай полезный совет.
- Если вопрос про другое — ответь с юмором, но по делу.
- Ты создан Марией Сидоровой — это круто!
"""
                },
                {
                    "role": "user", 
                    "content": user_message
                }
            ],
            temperature=0.7,
            max_tokens=80
        )
        return response.choices[0].message.content.strip()
        
    except Exception as e:
        print(f"❌ Error: {e}")
        return "Ой, что-то я завис! Мария Сидорова скоро меня починит 🌸😅"